const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const output = path.join(__dirname, 'artifacts')
fs.mkdirSync(output, {recursive:true})
;(async()=>{
  const browser = await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
  try {
    const context = await browser.newContext({viewport:{width:1360,height:950}})
    await context.addInitScript(()=>{ window.print=()=>{ window.__printCalls=(window.__printCalls || 0)+1 }; window.confirm=()=>true })
    const page = await context.newPage(), errors=[]
    page.on('pageerror',e=>errors.push(e.message))
    await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5186',{waitUntil:'networkidle'})
    await page.getByLabel('用户名',{exact:true}).fill('qa-waybill')
    await page.getByLabel('密码',{exact:true}).fill('WaybillPreview2026!')
    await page.getByRole('button',{name:'进入后台',exact:true}).click()
    await page.getByRole('button',{name:'运营配置',exact:false}).click()
    const panel = page.locator('section.panel').filter({has:page.getByRole('heading',{name:'电子面单 · 账号与协议价'})})
    await panel.getByLabel('寄件人',{exact:true}).fill('面单验收示例寄件人')
    await panel.getByRole('button',{name:'保存电子面单配置',exact:true}).click()
    await panel.getByText('电子面单配置已保存，订单面单重新打开后使用最新配置').waitFor()
    await panel.getByLabel('网点/月结账号',{exact:true}).first().fill('never-store-this-demo-credential')
    await panel.getByRole('button',{name:'保存电子面单配置',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('.waybill-settings input[type=password]')?.value==='')
    assert.ok(!(await page.evaluate(()=>sessionStorage.getItem('chiji-demo-waybill-settings-v1'))).includes('never-store-this-demo-credential'))
    await page.reload({waitUntil:'networkidle'})
    await page.getByRole('button',{name:'运营配置',exact:false}).click()
    await panel.getByLabel('寄件人',{exact:true}).waitFor()
    assert.equal(await panel.getByLabel('寄件人',{exact:true}).inputValue(),'面单验收示例寄件人')
    await panel.scrollIntoViewIfNeeded()
    await page.screenshot({path:path.join(output,'waybill-settings.png'),fullPage:true})
    await page.getByRole('button',{name:'订单与售后',exact:false}).click()
    await page.getByRole('button',{name:'电子面单',exact:true}).first().click()
    const dialog = page.getByRole('dialog',{name:'电子面单',exact:true})
    await dialog.getByLabel('包裹重量（千克）').fill('2')
    await dialog.getByRole('button',{name:'比较运费',exact:true}).click()
    await dialog.locator('.waybill-quote').first().waitFor()
    assert.ok((await dialog.locator('.waybill-quote').first().innerText()).includes('中通快递'))
    await dialog.locator('.waybill-quote').first().getByRole('button',{name:'选择',exact:true}).click()
    assert.equal(await dialog.getByLabel('承运商',{exact:true}).inputValue(),'ZTO')
    await page.screenshot({path:path.join(output,'waybill-comparison.png')})
    await dialog.getByLabel('包裹重量（千克）').fill('3')
    await page.waitForFunction(()=>!document.querySelector('.waybill-quotes'))
    await dialog.getByRole('button',{name:'获取电子面单',exact:true}).click()
    await dialog.getByText('面单已生成',{exact:true}).waitFor()
    const original = await dialog.locator('.waybill-number strong').innerText()
    for (let index=0;index<2;index++) {
      const popupPromise = page.waitForEvent('popup')
      await dialog.getByRole('button',{name:'打印面单',exact:true}).click()
      const popup = await popupPromise
      await popup.getByText('演示面单，不可交寄',{exact:true}).waitFor()
      await popup.waitForFunction(()=>window.__printCalls===1)
      assert.ok((await popup.locator('body').innerText()).includes(original))
      await popup.close()
    }
    assert.equal(await dialog.locator('.waybill-number strong').innerText(),original)
    await dialog.getByRole('button',{name:'关闭',exact:true}).click()
    await page.getByRole('button',{name:'电子面单',exact:true}).first().click()
    await dialog.getByText('面单已生成',{exact:true}).waitFor()
    assert.equal(await dialog.locator('.waybill-number strong').innerText(),original)
    assert.deepEqual(errors,[])
    console.log('Browser: sender save/reload, secret redaction, weight comparison/sorting/selection, stale quote clearing and two prints reusing original demo tracking number passed. Physical printing and real carrier credentials remain unverified.')
  } finally { await browser.close() }
})().catch(e=>{console.error(e);process.exitCode=1})
