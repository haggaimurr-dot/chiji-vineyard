const { chromium } = require('playwright')
const assert = require('node:assert/strict'), path = require('node:path'), fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  try {
    const page = await browser.newPage({ viewport: { width: 1360, height: 900 } }), errors = []
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5186', { waitUntil: 'networkidle' })
    await page.getByLabel('用户名', { exact: true }).fill('qa-dashboard')
    await page.getByLabel('密码', { exact: true }).fill('Dashboard2026!')
    await page.getByRole('button', { name: '进入后台', exact: true }).click()
    await page.getByRole('heading', { name: '销售趋势', exact: true }).waitFor()
    await page.getByLabel('开始日期', { exact: true }).fill('2026-09-18')
    await page.getByLabel('结束日期', { exact: true }).fill('2026-09-19')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await page.getByText('统计范围：2026-09-18 至 2026-09-19 · 订单当前状态', { exact: true }).waitFor()
    assert.match(await page.locator('.overview-metrics').innerText(), /¥460\.70/)
    assert.match(await page.locator('.repeat-rate').innerText(), /50\.0%/)
    assert.equal(await page.locator('.order-funnel-stage').count(), 3)
    assert.equal(await page.locator('.behavior-stage').count(), 5)
    assert.match(await page.locator('.overview-behavior').innerText(), /访问小程序/)
    assert.match(await page.locator('.overview-behavior').innerText(), /加入购物袋/)
    assert.match(await page.locator('.behavior-stage').first().innerText(), /4 人/)
    assert.match(await page.locator('.behavior-stage').nth(1).innerText(), /3 人/)
    assert.match(await page.locator('.behavior-stage').nth(2).innerText(), /2 人/)
    assert.match(await page.locator('.behavior-coverage').innerText(), /历史数据不补算/)
    await page.getByText('查看每日明细（2天）', { exact: true }).click()
    assert.equal(await page.locator('.overview-table tbody tr').count(), 2)
    assert.match(await page.locator('.overview-table tbody').innerText(), /¥81\.90/)
    const artifacts = path.join(__dirname, 'artifacts'); fs.mkdirSync(artifacts, { recursive: true })
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: path.join(artifacts, 'dashboard-1360.png'), fullPage: true })
    await page.getByLabel('开始日期', { exact: true }).fill('2026-09-20')
    await page.getByLabel('结束日期', { exact: true }).fill('2026-09-21')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await page.getByText('该期间暂无已支付订单。', { exact: true }).waitFor()
    assert.match(await page.locator('.overview-metrics').innerText(), /¥0\.00/)
    await page.getByText('该期间暂无已采集的访问用户。', { exact: true }).waitFor()
    assert.match(await page.locator('.overview-backlog').innerText(), /待发货\n1/)
    await page.getByLabel('开始日期', { exact: true }).fill('2026-09-22')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: '日期范围' }).waitFor()
    await page.getByRole('button', { name: '近30天', exact: true }).click()
    await page.getByRole('heading', { name: '销售趋势', exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log('Dashboard UI passed: login, custom range, income, repurchase, funnel, daily details, empty state, global backlog, invalid range, recovery, no page errors.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
