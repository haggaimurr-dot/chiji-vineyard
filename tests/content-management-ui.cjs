const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')

;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  try {
    const page = await browser.newPage({ viewport: { width: 1360, height: 900 } })
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5188', { waitUntil: 'networkidle' })
    await page.getByLabel('用户名', { exact: true }).fill('content-qa')
    await page.getByLabel('密码', { exact: true }).fill('ContentQA2026!')
    await page.getByRole('button', { name: '进入后台', exact: true }).click()
    await page.getByRole('button', { name: '课 种植内容', exact: true }).click()
    await page.getByRole('tab', { name: '标签库' }).click()
    await page.getByRole('button', { name: '＋ 新增标签' }).click()
    let dialog = page.getByRole('dialog')
    await dialog.getByLabel('名称', { exact: true }).fill('葡萄修剪')
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await page.locator('.content-card').filter({ hasText: '葡萄修剪' }).waitFor()
    await page.getByRole('tab', { name: '素材库' }).click()
    await page.getByRole('button', { name: '＋ 新增素材' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('名称', { exact: true }).fill('测试封面')
    await dialog.getByLabel('上传素材图片').setInputFiles(path.join(__dirname, '../miniprogram/assets/products/kyoho.jpg'))
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await page.locator('.content-card').filter({ hasText: '测试封面' }).waitFor()
    await page.getByRole('tab', { name: '内容列表' }).click()
    await page.getByRole('button', { name: '＋ 新建内容' }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByLabel('标题', { exact: true }).fill('修剪课堂验收')
    await dialog.getByLabel('摘要', { exact: true }).fill('种植内容功能验收')
    await dialog.getByRole('checkbox', { name: '葡萄修剪' }).check()
    await dialog.getByLabel('选择封面素材').selectOption({ label: '测试封面' })
    await dialog.locator('.tiptap').fill('修剪时保留健康枝条。')
    await dialog.getByRole('button', { name: '保存内容', exact: true }).click()
    let card = page.locator('.content-card').filter({ hasText: '修剪课堂验收' })
    await card.waitFor()
    await card.getByRole('button', { name: '提交审核', exact: true }).click()
    await card.getByText('待审核', { exact: true }).waitFor()
    await page.getByRole('tab', { name: /内容审核/ }).click()
    card = page.locator('.content-card').filter({ hasText: '修剪课堂验收' })
    await card.getByRole('button', { name: '审核内容', exact: true }).click()
    dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: '退回修改', exact: true }).click()
    await dialog.getByRole('alert').filter({ hasText: '请填写退回原因' }).waitFor()
    await dialog.getByLabel('审核意见').fill('请补充修剪时间')
    await dialog.getByRole('button', { name: '退回修改', exact: true }).click()
    await dialog.waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: '已退回', exact: true }).click()
    await card.getByText('审核意见：请补充修剪时间', { exact: true }).waitFor()
    await card.getByRole('button', { name: '重新提交', exact: true }).click()
    await page.getByRole('button', { name: '待审核', exact: true }).click()
    await card.getByRole('button', { name: '审核内容', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: '审核通过', exact: true }).click()
    await page.getByRole('button', { name: '已通过', exact: true }).click()
    await card.getByText('已通过', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(__dirname, 'artifacts/content-management-review.png') })
    await page.setViewportSize({ width: 1024, height: 768 })
    const overflow = await page.evaluate(() => [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > innerWidth + 1).map(e => ({ tag: e.tagName, class: e.className, right: e.getBoundingClientRect().right })))
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, JSON.stringify(overflow))
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('button', { name: '课 种植内容', exact: true }).click()
    await page.getByRole('tab', { name: '标签库' }).click()
    await page.locator('.content-card').filter({ hasText: '葡萄修剪' }).waitFor()
    await page.getByRole('tab', { name: '素材库' }).click()
    await page.locator('.content-card').filter({ hasText: '测试封面' }).waitFor()
    assert.deepEqual(errors, [])
    console.log('Content management UI: tag creation, image upload, editor associations, review rejection/resubmission/approval, reload persistence and 1024px layout passed')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
