const {chromium} = require('playwright')
const {spawn} = require('node:child_process')
const path = require('node:path'), fs = require('node:fs'), assert = require('node:assert/strict')
const root = path.resolve(__dirname,'..'), artifacts = path.join(__dirname,'artifacts')
fs.mkdirSync(artifacts,{recursive:true})
async function main() {
 const port=5297, server=spawn(process.execPath,[path.join(root,'node_modules/vite/bin/vite.js'),'--host','127.0.0.1','--port',String(port),'--strictPort'],{cwd:path.join(root,'admin'),env:{...process.env,VITE_USE_MOCK:'true'},windowsHide:true,stdio:'pipe'})
 let browser
 try {
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Vite startup timeout')),20000);server.stdout.on('data',data=>{if(String(data).includes('127.0.0.1')){clearTimeout(timer);resolve()}});server.on('error',e=>{clearTimeout(timer);reject(e)});server.on('exit',code=>{if(code){clearTimeout(timer);reject(new Error('Vite exited '+code))}})})
  browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
  const page=await browser.newPage({viewport:{width:1360,height:1000}}), errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:'+port,{waitUntil:'networkidle'})
  await page.getByLabel('用户名',{exact:true}).fill('qa-after-sales')
  await page.getByLabel('密码',{exact:true}).fill('AfterSales2026!')
  await page.getByRole('button',{name:'进入后台',exact:true}).click()
  await page.getByRole('button',{name:'订单与售后',exact:false}).click()
  const panel=page.locator('.after-sales-panel')
  await panel.locator('.ticket-item').first().waitFor()
  assert.match(await panel.locator('.ticket-item').first().innerText(),/未读用户消息|处理已超时/)
  await panel.locator('.ticket-item').first().click()
  const due=new Date(Date.now()+72*3600000); const localDue=new Date(due.getTime()-due.getTimezoneOffset()*60000).toISOString().slice(0,16)
  await panel.getByLabel('调整处理期限（未来30天内；留空沿用）').fill(localDue)
  await panel.locator('input[type=file]').setInputFiles({name:'evidence.png',mimeType:'image/png',buffer:Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aPrsAAAAASUVORK5CYII=','base64')})
  await panel.getByLabel('负责人（管理员用户名）').fill('qa-after-sales')
  await panel.getByLabel('处理状态').selectOption('PROCESSING')
  await panel.getByLabel('回复 / 处理结果（用户可见）').fill('已核实问题，正在处理。')
  await panel.getByRole('button',{name:'保存并回复',exact:true}).click()
  await panel.getByRole('status').filter({hasText:'工单已更新'}).waitFor()
  await panel.locator('.evidence img').waitFor()
  assert.match(await panel.locator('.evidence').innerText(),/evidence.png/)
  assert.doesNotMatch(await panel.locator('.ticket-item').first().innerText(),/未读用户消息/)
  await panel.getByLabel('处理状态').selectOption('RESOLVED')
  await panel.getByLabel('回复 / 处理结果（用户可见）').fill('售后问题已处理完成。')
  await panel.getByRole('button',{name:'保存并回复',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.ticket-detail h4')?.textContent.includes('已解决'))
  await panel.scrollIntoViewIfNeeded()
  await page.screenshot({path:path.join(artifacts,'after-sales-ui-1360.png')})
  await page.setViewportSize({width:1024,height:900})
  await page.screenshot({path:path.join(artifacts,'after-sales-ui-1024.png')})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await panel.getByLabel('处理状态').selectOption('CLOSED')
  await panel.getByLabel('回复 / 处理结果（用户可见）').fill('工单结束。')
  await panel.getByRole('button',{name:'保存并回复',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.ticket-detail h4')?.textContent.includes('已关闭'))
  assert.equal(await panel.getByRole('button',{name:'保存并回复',exact:true}).count(),0)
  await panel.getByRole('button',{name:'新建工单',exact:true}).click()
  await panel.getByLabel('订单',{exact:true}).selectOption('o-3')
  await panel.getByLabel('问题类型').selectOption('DELIVERY')
  await panel.getByLabel('问题描述').fill('新的配送问题需要跟进。')
  await panel.getByRole('button',{name:'创建工单',exact:true}).click()
  await panel.getByRole('status').filter({hasText:'工单已创建'}).waitFor()
  const autoButton=page.getByRole('button',{name:'自动开票',exact:true})
  await autoButton.click()
  await page.getByText('自动开票完成',{exact:true}).first().waitFor()
  const download=page.getByRole('button',{name:'下载发票',exact:true})
  const downloadPromise=page.waitForEvent('download');await download.click();const file=await downloadPromise
  assert.match(file.suggestedFilename(),/^DEMO-/)
  const output=path.join(artifacts,'auto-invoice-DEMO.pdf');await file.saveAs(output)
  assert.match(fs.readFileSync(output,'utf8'),/DEMO ONLY/)
  assert.deepEqual(errors,[])
  console.log('Admin UI: assignment, reply, resolution, closure, new ticket, automatic invoice/download and 1024px layout passed.')
 } finally {if(browser)await browser.close();server.kill()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
