const { chromium } = require('playwright')
const assert = require('node:assert/strict')

;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  try {
    const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, timezoneId: 'Asia/Shanghai' })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5173', { waitUntil: 'networkidle' })
    await page.getByLabel('用户名', { exact: true }).fill('operations-qa')
    await page.getByLabel('密码', { exact: true }).fill('OperationsQA2026!')
    await page.getByRole('button', { name: '进入后台', exact: true }).click()
    await page.getByRole('button', { name: '运营配置', exact: false }).click()
    const shipping = page.locator('#shipping-templates')
    await page.getByRole('link', { name: '分地区运费模板', exact: true }).click()
    await shipping.getByRole('button', { name: '新增地区模板' }).click()
    const template = shipping.locator('fieldset').first()
    await template.getByLabel('名称', { exact: true }).fill('浙江配送')
    await template.getByLabel('省份', { exact: true }).fill('浙江省')
    await template.getByLabel('基础运费（元）', { exact: true }).fill('10')
    await template.getByLabel('包邮门槛', { exact: false }).fill('200')
    await template.getByLabel('每超出一件运费（元）', { exact: true }).fill('2')
    await template.getByLabel('地区附加费（元）', { exact: true }).fill('3')
    await shipping.getByLabel('试算省份', { exact: true }).fill('浙江省')
    await shipping.getByLabel('商品件数', { exact: true }).fill('3')
    await shipping.getByRole('status').filter({ hasText: '运费 ¥17.00' }).waitFor()
    await shipping.getByLabel('商品金额（元）', { exact: true }).fill('200')
    await shipping.getByRole('status').filter({ hasText: '运费 ¥3.00' }).waitFor()
    await template.getByRole('button', { name: '复制模板' }).click()
    const copy = shipping.locator('fieldset').nth(1)
    assert.equal(await copy.getByLabel('省份', { exact: true }).inputValue(), '')
    assert.equal(await copy.getByLabel('基础运费（元）', { exact: true }).inputValue(), '10.00')
    await copy.getByLabel('省份', { exact: true }).fill('江苏省')
    await shipping.getByRole('button', { name: '保存配置', exact: true }).click()
    await shipping.getByRole('status').filter({ hasText: '配置已保存' }).waitFor()

    await page.getByRole('link', { name: '活动管理', exact: true }).click()
    const activities = page.locator('#activity-management')
    // Remove demo activities to verify creation, ordering, deletion and persistence.
    while (await activities.getByRole('button', { name: '删除活动' }).count()) await activities.getByRole('button', { name: '删除活动' }).first().click()
    for (const title of ['采摘体验', '果园参观']) {
      await activities.getByRole('button', { name: '新增活动', exact: true }).click()
      const item = activities.locator('.activity-fields > fieldset').last()
      await item.getByLabel('活动标题', { exact: true }).fill(title)
      await item.getByLabel('活动简介', { exact: true }).fill('当季葡萄体验')
      await item.getByLabel('活动详情', { exact: true }).fill('到果园了解葡萄种植并体验采摘。')
      await item.getByLabel('活动开始日期', { exact: true }).fill('2026-10-01')
      await item.getByLabel('活动结束日期', { exact: true }).fill('2026-10-31')
      await item.getByLabel('开放活动预约', { exact: true }).check()
    }
    await activities.getByRole('button', { name: '下移', exact: true }).first().click()
    assert.equal(await activities.getByLabel('活动标题', { exact: true }).first().inputValue(), '果园参观')
    await activities.getByRole('button', { name: '删除活动' }).last().click()
    await activities.getByRole('button', { name: '保存活动与首页' }).click()
    await page.getByRole('status').filter({ hasText: '首页配置已保存并回读确认' }).waitFor()
    await page.locator('.preview-panel').getByRole('button', { name: '看看果园近况 ＋', exact: true }).click()
    await page.locator('.preview-panel').getByText('果园参观', { exact: true }).waitFor()
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('button', { name: '运营配置', exact: false }).click()
    await activities.getByLabel('活动标题', { exact: true }).first().waitFor()
    assert.equal(await activities.getByLabel('活动标题', { exact: true }).first().inputValue(), '果园参观')
    assert.equal(await activities.getByLabel('活动标题', { exact: true }).count(), 1)
    assert.equal(await activities.getByLabel('开放活动预约', { exact: true }).isChecked(), true)
    assert.equal(await shipping.getByRole('button', { name: '删除模板' }).count(), 2)
    for (const width of [1360, 1024]) {
      await page.setViewportSize({ width, height: 900 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    }
    assert.deepEqual(errors, [])
    console.log('Operations configuration UI passed: regional quotes, template copy/save/reload, activity create/order/delete/reservation/save/preview/reload, and responsive layout.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
