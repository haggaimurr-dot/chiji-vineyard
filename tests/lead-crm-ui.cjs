const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
;(async () => {
 const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
 try {
  const page = await browser.newPage({ viewport: { width: 1360, height: 900 } }), errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5187', { waitUntil: 'networkidle' })
  await page.getByLabel('用户名', { exact: true }).fill('qa-crm')
  await page.getByLabel('密码', { exact: true }).fill('CrmTesting2026!')
  await page.getByRole('button', { name: '进入后台', exact: true }).click()
  await page.getByRole('button', { name: /合作线索/ }).click()
  await page.getByRole('region', { name: '成交漏斗' }).waitFor()
  await page.getByRole('button', { name: '客户档案 / 跟进', exact: true }).first().click()
  const drawer = page.locator('.lead-dialog')
  await drawer.getByLabel('客户邮箱', { exact: true }).fill('buyer@example.com')
  await drawer.getByLabel('所属行业', { exact: true }).fill('社区零售')
  await drawer.getByLabel('客户地址', { exact: true }).fill('杭州测试地址')
  await drawer.getByLabel('档案备注', { exact: true }).fill('每周采购两次')
  await drawer.getByLabel('商机金额（人民币元）', { exact: true }).fill('12345.67')
  await drawer.getByRole('button', { name: '保存跟进', exact: true }).click()
  await drawer.getByText('已保存，本次操作已记入跟进历史。').waitFor()
  await drawer.locator('.history-change-tags').getByText('客户档案', { exact: true }).waitFor()
  assert.match(await drawer.locator('.lead-history').innerText(), /客户档案/)
  assert.match(await drawer.locator('.lead-history').innerText(), /12,345.67/)
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.funnel-totals').waitFor()
  assert.match(await page.locator('.crm-funnel').innerText(), /12,345.67/)
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('button', { name: /合作线索/ }).click()
  await page.getByRole('button', { name: '客户档案 / 跟进', exact: true }).first().click()
  assert.equal(await drawer.getByLabel('客户邮箱', { exact: true }).inputValue(), 'buyer@example.com')
  assert.equal(await drawer.getByLabel('商机金额（人民币元）', { exact: true }).inputValue(), '12345.67')
  await drawer.getByRole('button', { name: '关闭', exact: true }).click()
  const dir = path.join(__dirname, '..', 'docs', 'test-evidence'); fs.mkdirSync(dir, { recursive: true })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: path.join(dir, 'lead-crm.png'), fullPage: true })
  await page.setViewportSize({ width: 1024, height: 900 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  assert.deepEqual(errors, [])
  console.log('CRM browser save, history, funnel amounts, reload persistence and 1024px layout passed.')
 } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
