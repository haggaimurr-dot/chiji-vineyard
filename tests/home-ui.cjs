const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const artifacts = path.join(__dirname, 'artifacts')
fs.mkdirSync(artifacts, { recursive: true })
const results = { checks: [], screenshots: [], errors: [] }
// Coverage: packaged images, upload/save/readback/reload, bad file retains image,
// failed remote image, preview snapshots, 1360/1024 viewport fit.
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  try {
    const context = await browser.newContext({ viewport: { width: 1360, height: 900 }, timezoneId: 'Asia/Shanghai' })
    const page = await context.newPage()
    page.on('pageerror', e => results.errors.push(e.message))
    await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5181', { waitUntil: 'networkidle' })
    await page.getByLabel('用户名', { exact: true }).fill('qa-home')
    await page.getByLabel('密码', { exact: true }).fill('HomePreview2026!')
    await page.getByRole('button', { name: '进入后台', exact: true }).click()
    await page.getByRole('button', { name: '运营配置', exact: false }).click()
    const form = page.locator('form.operations-config').first()
    await form.waitFor()
    await form.getByRole('button', { name: '预览当前编辑', exact: true }).click()
    const preview = page.locator('.preview-panel')
    await preview.waitFor()
    assert.equal(await preview.locator('.preview-content').count(), 0, 'operational modules start collapsed')
    await preview.getByRole('button', { name: '看看果园近况 ＋', exact: true }).click()
    await page.waitForFunction(() => {
      const images = [...document.querySelectorAll('.preview-hero>img,.preview-panel .product-card>img')]
      return images.length === 4 && images.every(img => img.complete && img.naturalWidth > 0)
    })
    results.checks.push('轮播和三款推荐商品本地 mock 图片加载成功')
    const capture = async name => {
      await preview.scrollIntoViewIfNeeded()
      await page.screenshot({ path: path.join(artifacts, `home-ui-${name}.png`), scale: 'css' })
      results.screenshots.push(`home-ui-${name}.png`)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    }
    await capture('mock-1360')
    await preview.getByRole('button', { name: '关闭预览' }).click()
    const fileInput = page.getByLabel('上传轮播图片 1', { exact: true })
    const imageInput = form.locator('input[placeholder="https://…"]').first()
    const original = await imageInput.inputValue()
    await fileInput.setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') })
    await page.getByRole('alert').filter({ hasText: '请上传 JPG' }).waitFor()
    assert.equal(await imageInput.inputValue(), original)
    await fileInput.setInputFiles({ name: 'too-large.jpg', mimeType: 'image/jpeg', buffer: Buffer.alloc(4 * 1024 * 1024 + 1) })
    await page.getByRole('alert').filter({ hasText: '不能超过 4MB' }).waitFor()
    assert.equal(await imageInput.inputValue(), original)
    results.checks.push('错误格式与超大文件保留原图')
    await fileInput.setInputFiles(path.join(__dirname, '../miniprogram/assets/products/kyoho.jpg'))
    await page.getByRole('status').filter({ hasText: '轮播图片已替换' }).waitFor()
    assert.match(await imageInput.inputValue(), /^data:image\/jpeg;base64,/)
    await form.getByRole('button', { name: '保存并预览首页', exact: true }).click()
    await page.getByRole('status').filter({ hasText: '首页配置已保存并回读确认' }).waitFor()
    await preview.getByText('已回读保存值', { exact: true }).waitFor()
    await page.waitForFunction(() => document.querySelector('.preview-hero>img')?.naturalWidth > 0)
    await capture('uploaded-1360')
    results.checks.push('上传图片、保存并回读确认、保存预览展示新图')
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('button', { name: '运营配置', exact: false }).click()
    await form.waitFor()
    assert.match(await imageInput.inputValue(), /^data:image\/jpeg;base64,/)
    results.checks.push('mock 配置刷新后保持上传素材')
    await page.route('https://fixture.example/**', route => route.abort())
    await imageInput.fill('https://fixture.example/missing.jpg')
    await form.getByRole('button', { name: '预览当前编辑', exact: true }).click()
    await preview.getByText('图片暂不可用', { exact: true }).first().waitFor()
    await capture('failed-image-1360')
    await page.setViewportSize({ width: 1024, height: 900 })
    await capture('failed-image-1024')
    results.checks.push('坏链接显示提示，1360/1024 页面无水平溢出')
    assert.deepEqual(results.errors, [])
    console.log(JSON.stringify(results, null, 2))
  } finally {
    fs.writeFileSync(path.join(artifacts, 'home-ui-results.json'), JSON.stringify(results, null, 2))
    await browser.close()
  }
})().catch(e => { console.error(e); process.exitCode = 1 })
