const {chromium}=require('playwright'),assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs')
;(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_BROWSER||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'})
 try{
  const page=await browser.newPage({viewport:{width:1360,height:900}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(process.env.ADMIN_UI_URL||'http://127.0.0.1:5184',{waitUntil:'networkidle'})
  await page.getByLabel('用户名',{exact:true}).fill('qa-inventory');await page.getByLabel('密码',{exact:true}).fill('Inventory2026!')
  await page.getByRole('button',{name:'进入后台',exact:true}).click();await page.getByRole('button',{name:/商品与库存/}).click()
  await page.getByRole('button',{name:/低库存告警/}).click()
  await page.getByText('暂无低库存告警',{exact:true}).waitFor()
  await page.getByLabel('仅查看告警规格').uncheck()
  const row=page.locator('.inventory-table tbody tr').filter({hasText:'双拼葡萄礼盒'})
  await row.getByRole('button',{name:'设置阈值'}).click();await page.getByLabel('告警阈值',{exact:true}).fill('30')
  await page.locator('.inventory-drawer').getByRole('button',{name:'保存',exact:true}).click()
  await page.getByText('1 个规格需要补货',{exact:true}).waitFor()
  await page.getByLabel('仅查看告警规格').check();await row.getByRole('button',{name:'调整库存'}).click()
  await page.getByLabel('调整后可售库存').fill('40');await page.getByLabel('调整原因',{exact:true}).fill('浏览器验收补货')
  await page.locator('.inventory-drawer').getByRole('button',{name:'保存',exact:true}).click();await page.getByText('暂无低库存告警',{exact:true}).waitFor()
  await page.getByRole('button',{name:'库存流水',exact:true}).click();await page.getByText('浏览器验收补货',{exact:true}).waitFor()
  assert.match(await page.locator('.inventory-table tbody').innerText(),/30 → 40/)
  await page.reload({waitUntil:'networkidle'});await page.getByRole('button',{name:/商品与库存/}).click();await page.getByRole('button',{name:'库存流水',exact:true}).click();await page.getByText('浏览器验收补货',{exact:true}).waitFor()
  const artifacts=path.join(__dirname,'artifacts');fs.mkdirSync(artifacts,{recursive:true})
  await page.screenshot({path:path.join(artifacts,'inventory-ledger.png'),fullPage:true})
  await page.setViewportSize({width:1024,height:900});await page.getByRole('button',{name:/低库存告警/}).click();await page.getByLabel('仅查看告警规格').uncheck()
  await page.getByRole('button',{name:'刷新',exact:true}).click();await page.getByText('库存充足',{exact:true}).first().waitFor()
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.screenshot({path:path.join(artifacts,'inventory-alerts.png'),fullPage:true})
  assert.deepEqual(errors,[]);console.log('Inventory UI passed: threshold save, low-stock alert, replenishment recovery, ledger, reload persistence, 1024px layout, no page errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
