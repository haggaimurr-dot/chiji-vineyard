const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' })
  try {
    const page = await browser.newPage({ viewport: { width: 1360, height: 900 } })
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    await page.goto(process.env.ADMIN_UI_URL || 'http://127.0.0.1:5197', { waitUntil: 'networkidle' })
    await page.getByLabel('用户名', { exact: true }).fill('classroom-qa')
    await page.getByLabel('密码', { exact: true }).fill('ClassroomQA2026!')
    await page.getByRole('button', { name: '进入后台', exact: true }).click()
    await page.getByRole('button', { name: '课 种植内容', exact: true }).click()
    await page.getByRole('tab', { name: '课堂问答', exact: true }).click()
    const card = page.locator('.qa-card')
    await card.waitFor()
    await card.getByLabel('老师回复').fill('先记录近期天气、土壤湿度、枝条长势，再结合本节课程安排操作。')
    await card.getByRole('button', { name: '提交回复', exact: true }).click()
    await page.getByText('暂无待回复的问题', { exact: true }).waitFor()
    await page.locator('.qa-filters select').selectOption('answered')
    await card.waitFor()
    assert.match(await card.innerText(), /先记录近期天气/)
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('button', { name: '课 种植内容', exact: true }).click()
    await page.getByRole('tab', { name: '课堂问答', exact: true }).click()
    await page.locator('.qa-filters select').selectOption('answered')
    await card.waitFor()
    assert.match(await card.innerText(), /先记录近期天气/)
    await page.screenshot({ path: path.join(__dirname, 'artifacts/classroom-questions-1360.png'), fullPage: true })
    await page.setViewportSize({ width: 1024, height: 900 })
    await page.screenshot({ path: path.join(__dirname, 'artifacts/classroom-questions-1024.png'), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    assert.deepEqual(errors, [])
    console.log('Classroom questions UI passed: submit, filter, reload persistence, responsive layout and no browser errors')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
