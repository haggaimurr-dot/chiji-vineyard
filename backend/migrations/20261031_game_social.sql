-- 小游戏排行榜与好友助力
CREATE TABLE IF NOT EXISTS game_scores (
 owner VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 nickname VARCHAR(64) NOT NULL DEFAULT '',
 score INT NOT NULL DEFAULT 0,
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 INDEX idx_game_score (score DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS game_helps (
 helper VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 target VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 day CHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY (helper,target,day),
 INDEX idx_help_target_day (target,day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
