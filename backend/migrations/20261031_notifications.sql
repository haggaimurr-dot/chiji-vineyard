-- 通知中心
CREATE TABLE IF NOT EXISTS notifications (
 id VARCHAR(80) PRIMARY KEY,
 openid VARCHAR(80) NOT NULL,
 channel VARCHAR(16) NOT NULL,
 kind VARCHAR(40) NOT NULL,
 title VARCHAR(120) NOT NULL DEFAULT '',
 payload JSON NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'QUEUED',
 error VARCHAR(300) NOT NULL DEFAULT '',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 sent_at DATETIME(3) NULL,
 INDEX idx_notify_status (status,created_at),
 INDEX idx_notify_openid (openid,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notification_prefs (
 openid VARCHAR(80) NOT NULL,
 channel VARCHAR(16) NOT NULL,
 kind VARCHAR(40) NOT NULL,
 enabled TINYINT(1) NOT NULL DEFAULT 1,
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 PRIMARY KEY (openid,channel,kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notification_subs (
 openid VARCHAR(80) NOT NULL,
 kind VARCHAR(40) NOT NULL,
 template_id VARCHAR(120) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'ACCEPTED',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY (openid,kind)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
